// Posts approved clips to every connected account of the clip's campaign. Official APIs only:
// YouTube Data API (resumable upload); TikTok and Instagram via PostPeer when POSTPEER_API_KEY is set, else TikTok Content Posting API.
import { readFileSync, statSync } from 'node:fs';
import { and, eq, gte } from 'drizzle-orm';
import { loadSettings } from '../../config.ts';
import type { Db } from '../../db/client.ts';
import { accounts, clips, moments, posts } from '../../db/schema.ts';
import { logger } from '../../log.ts';
import { enqueue } from '../../queue/queue.ts';
import type { Platform } from '../../review/setup.ts';
import { sourceContext } from '../vod-clipper/analyze.ts';
import { accessToken, hasToken } from './oauth.ts';
import { hasPostpeer, postpeerPublish } from './postpeer.ts';

const log = logger('publisher');
const TIKTOK_MAX_ONE_CHUNK = 64 * 1024 * 1024;

/** First sentence of the transcript as a fallback title (shortcut: until hooks/titles are generated by Ollama or Haiku). */
export function fallbackTitle(transcript: string | null, streamer: string): string {
  const s = (transcript ?? '').trim().split(/(?<=[.!?])\s/)[0]?.replace(/[<>]/g, '').trim() ?? '';
  if (s.length < 8) return `${streamer} moment`;
  const t = s.length > 70 ? `${s.slice(0, 70).replace(/\s+\S*$/, '')}…` : s;
  return t[0].toUpperCase() + t.slice(1);
}

/** Per-platform text: YouTube has a 100-char title plus description, TikTok one caption. */
export function postText(platform: Platform, o: { title: string; streamer: string; tag: string; disclosure: string | null }) {
  const tags = [o.disclosure, o.tag, `#${o.streamer.replace(/\W/g, '')}`, platform === 'youtube' ? '#shorts' : '#fyp'].filter(Boolean).join(' ');
  return platform === 'youtube'
    ? { title: o.title.slice(0, 100), description: tags }
    : { title: `${o.title} ${tags}`.slice(0, 2200), description: '' };
}

/** Next allowed time when the account hit its daily limit: tomorrow 10:00 local. */
export function nextDay(now: Date): Date {
  const d = new Date(now);
  d.setDate(d.getDate() + 1);
  d.setHours(10, 0, 0, 0);
  return d;
}

const viaPostpeer = (platform: string) => platform !== 'youtube' && hasPostpeer();

/** Called on approve: one publish job per connected account of the clip's campaign. */
export function queuePublish(db: Db, clipId: number) {
  const clip = db.select().from(clips).where(eq(clips.id, clipId)).get();
  const moment = clip && db.select().from(moments).where(eq(moments.id, clip.momentId)).get();
  if (!moment) return;
  const { source } = sourceContext(db, moment.sourceId);
  if (!source.streamerId) return;
  const on = loadSettings().platforms;
  for (const a of db.select().from(accounts).where(eq(accounts.streamerId, source.streamerId)).all()) {
    if (on[a.platform] && (viaPostpeer(a.platform) || hasToken(a.id))) enqueue(db, 'clip.publish', { clipId, accountId: a.id });
  }
}

async function youtube(token: string, file: string, t: { title: string; description: string }, paid: boolean, placement = true): Promise<{ externalId: string; url: string }> {
  const size = statSync(file).size;
  const init = await fetch(`https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status${placement ? ',paidProductPlacementDetails' : ''}`, {
    method: 'POST',
    headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json; charset=UTF-8', 'x-upload-content-type': 'video/mp4', 'x-upload-content-length': String(size) },
    body: JSON.stringify({
      snippet: { title: t.title, description: t.description, categoryId: '20' }, // 20 = Gaming
      status: { privacyStatus: 'public', selfDeclaredMadeForKids: false },
      ...(placement && { paidProductPlacementDetails: { hasPaidProductPlacement: paid } }),
    }),
  });
  const loc = init.headers.get('location');
  // If YouTube rejects the paid-promotion field, upload without it: the #ad in the description still discloses.
  if (init.status === 400 && placement) {
    log.warn(`YouTube refused paidProductPlacementDetails, retrying without it: ${(await init.text()).slice(0, 200)}`);
    return youtube(token, file, t, paid, false);
  }
  if (!init.ok || !loc) throw new Error(`YouTube upload start failed: ${init.status} ${(await init.text()).slice(0, 300)}`);
  const up = await fetch(loc, { method: 'PUT', headers: { 'content-type': 'video/mp4' }, body: readFileSync(file) });
  const v = await up.json().catch(() => ({})) as { id?: string };
  if (!up.ok || !v.id) throw new Error(`YouTube upload failed: ${up.status}`);
  return { externalId: v.id, url: `https://youtube.com/shorts/${v.id}` };
}

export async function tiktokApi<T>(token: string, path: string, body: unknown): Promise<T> {
  const r = await fetch(`https://open.tiktokapis.com/v2/${path}`, {
    method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json; charset=UTF-8' }, body: JSON.stringify(body) });
  const j = await r.json().catch(() => ({})) as { data?: T; error?: { code?: string; message?: string } };
  if (j.error?.code !== 'ok' || !j.data) throw new Error(`TikTok ${path} failed: ${j.error?.code ?? r.status} ${j.error?.message ?? ''}`);
  return j.data;
}

async function tiktok(token: string, file: string, t: { title: string }, paid: boolean) {
  const size = statSync(file).size;
  if (size > TIKTOK_MAX_ONE_CHUNK) throw new Error(`clip is ${(size / 1e6).toFixed(0)} MB, over TikTok's one-chunk limit`);
  // Until TikTok approves the app, only private posts are allowed. Branded content cannot be private.
  const privacy = loadSettings().publish?.tiktokPublic ? 'PUBLIC_TO_EVERYONE' : 'SELF_ONLY';
  const init = await tiktokApi<{ publish_id: string; upload_url: string }>(token, 'post/publish/video/init/', {
    post_info: { title: t.title, privacy_level: privacy, disable_duet: false, disable_comment: false, disable_stitch: false,
      brand_content_toggle: paid && privacy !== 'SELF_ONLY', brand_organic_toggle: false },
    source_info: { source: 'FILE_UPLOAD', video_size: size, chunk_size: size, total_chunk_count: 1 },
  });
  const up = await fetch(init.upload_url, { method: 'PUT', headers: { 'content-type': 'video/mp4', 'content-range': `bytes 0-${size - 1}/${size}` }, body: readFileSync(file) });
  if (!up.ok) throw new Error(`TikTok upload failed: ${up.status}`);
  return { externalId: `publish:${init.publish_id}`, url: null }; // the tracker swaps in the post id and link once TikTok is done
}

export async function publishClip(db: Db, { clipId, accountId }: { clipId: number; accountId: number }) {
  const clip = db.select().from(clips).where(eq(clips.id, clipId)).get();
  const account = db.select().from(accounts).where(eq(accounts.id, accountId)).get();
  if (!clip || !account) throw new Error(`clip ${clipId} or account ${accountId} not found`);
  if (clip.status !== 'approved' && clip.status !== 'posted') return log.info(`clip ${clipId} not approved, not posting`);
  const prev = db.select().from(posts).where(and(eq(posts.clipId, clipId), eq(posts.accountId, accountId))).get();
  if (prev) {
    if (!prev.externalId) throw new Error(`clip ${clipId} may already be on account ${accountId} (the program stopped mid-upload). Check the account; delete post row ${prev.id} to post again.`);
    return;
  }
  const settings = loadSettings();
  if (!settings.platforms[account.platform]) return log.info(`${account.platform} is off in settings, clip ${clipId} not posted`);

  const now = new Date();
  const today = new Date(now); today.setHours(0, 0, 0, 0);
  const done = db.select().from(posts).where(and(eq(posts.accountId, accountId), gte(posts.postedAt, today))).all().length;
  if (done >= settings.limits.maxPostsPerAccountPerDay) {
    enqueue(db, 'clip.publish', { clipId, accountId }, { runAt: nextDay(now) });
    return log.info(`account ${accountId} hit its daily limit, clip ${clipId} moved to tomorrow`);
  }

  const moment = db.select().from(moments).where(eq(moments.id, clip.momentId)).get()!;
  const { cfg } = sourceContext(db, moment.sourceId);
  const paid = cfg.campaign?.disclosure ?? settings.clip.disclosure;
  const text = postText(account.platform as Platform, {
    title: clip.title ?? fallbackTitle(clip.transcript, cfg.name), streamer: cfg.name, tag: cfg.tag, disclosure: paid ? settings.clip.disclosureText : null });
  const pp = viaPostpeer(account.platform);
  if (!pp && account.platform === 'instagram') return log.warn('Instagram posting needs POSTPEER_API_KEY');
  const token = pp ? '' : await accessToken(accountId, account.platform as Platform);
  // Reserve the post row before uploading: if the process dies mid-upload, the retry sees the row and does not post twice.
  const postId = db.insert(posts).values({ clipId, accountId, platform: account.platform, postedAt: now }).returning({ id: posts.id }).get().id;
  let r: { externalId: string; url: string | null };
  try {
    r = pp ? await postpeerPublish({ platform: account.platform as 'tiktok' | 'instagram', accountName: account.name, file: clip.filePath, content: text.title, paid, key: `clip-${clipId}-account-${accountId}` })
      : account.platform === 'youtube' ? await youtube(token, clip.filePath, text, paid) : await tiktok(token, clip.filePath, text, paid);
  } catch (e) {
    db.delete(posts).where(eq(posts.id, postId)).run(); // clean failure: nothing went up, so the retry may post again
    throw e;
  }
  db.update(posts).set({ url: r.url, externalId: r.externalId }).where(eq(posts.id, postId)).run();
  if (r.url) enqueue(db, 'post.submit', { postId });
  db.update(clips).set({ status: 'posted' }).where(eq(clips.id, clipId)).run();
  log.info(`clip ${clipId} posted to ${account.platform} account ${accountId}`);
}
